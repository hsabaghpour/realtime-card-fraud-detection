"""Generate the README's results section from reports/metrics.json.

Every number in the README must come from a pipeline run, never be typed by
hand. ``sentinelpay readme-results`` rewrites the block between the markers
below with the latest metrics.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

START = "<!-- RESULTS:START -->"
END = "<!-- RESULTS:END -->"

PATTERN_NAMES = {
    "card_testing": "Card testing",
    "impossible_travel": "Impossible travel",
    "high_amount": "High amount",
    "night_burst": "Night burst",
    "compromised_merchant": "Compromised merchant",
}


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x:.1%}"


def render_results(m: dict[str, Any]) -> str:
    """Markdown results block for the README."""
    t = m["split"]["test"]
    lg, lr, ru = (m["models"][k] for k in ("lightgbm", "logistic_regression", "rules"))
    costs = m["costs"]

    def row(name: str, x: dict[str, Any]) -> str:
        a = x["at_threshold"]
        auc = f"{x['pr_auc']:.3f}" if "pr_auc" in x else "—"
        r05 = _pct(x.get("recall_at_fpr", {}).get("0.5%"))
        return (
            f"| {name} | {auc} | {r05} | {_pct(a['recall'])} | {_pct(a['precision'])} | "
            f"{a['alerts_per_day']:.1f} | ${a['expected_cost']:,.0f} |"
        )

    lines = [
        START,
        "",
        f"_Generated by `sentinelpay readme-results` from `reports/metrics.json` "
        f"({m['generated_at']}). Test window **{t['start']} → {t['end']}**: "
        f"{t['rows']:,} transactions, {t['frauds']:,} frauds, never seen in training. "
        "**Synthetic data**: absolute numbers are higher than on real fraud data; "
        "the comparison between approaches is the point._",
        "",
        "| Approach | PR-AUC | Fraud caught @ 0.5% false alarms | Fraud caught | "
        "Alerts that are fraud | Alerts / day | Expected cost |",
        "|---|---|---|---|---|---|---|",
        row("**LightGBM (champion)**", lg),
        row("Logistic regression", lr),
        row("Rules engine", ru),
        f"| No model | — | — | 0% | — | 0 | ${m['no_model_cost']:,.0f} |",
        "",
        f"Expected cost = missed frauds × ${costs['missed_fraud']:,.0f} + alerts × "
        f"${costs['alert_review']:,.0f}. The model saves **${m['savings']['vs_rules']:,.0f}** "
        f"vs. the rules engine over {t['days']} days.",
        "",
        "| Fraud caught by attack type | LightGBM | Logistic regression | Rules |",
        "|---|---|---|---|",
    ]
    for key, name in PATTERN_NAMES.items():
        vals = [_pct(x["recall_by_pattern"].get(key)) for x in (lg, lr, ru)]
        lines.append(f"| {name} | {' | '.join(vals)} |")
    lines += ["", END]
    return "\n".join(lines)


def update_readme(readme: Path, metrics: dict[str, Any]) -> bool:
    """Replace the results block in ``readme``. Returns False if markers are missing."""
    text = readme.read_text()
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        return False
    readme.write_text(pattern.sub(lambda _: render_results(metrics), text))
    return True
